// Regenerates src/profile.ts from @garmin/fitsdk. Only message numbers and names are copied.
// Usage: node scripts/gen-profile.mjs
import { writeFileSync } from 'node:fs';
import { Profile } from '@garmin/fitsdk';

const entries = Object.entries(Profile.MesgNum)
  .map(([name, num]) => [num, name.toLowerCase()])
  .sort((a, b) => a[0] - b[0]);
const version = `${Profile.version.major}.${Profile.version.minor}`;
const lines = entries.map(([num, name]) => `  [${num}, '${name}'],`).join('\n');
writeFileSync(
  new URL('../src/profile.ts', import.meta.url),
  `// Generated by scripts/gen-profile.mjs from FIT profile ${version}. Do not edit.

/** Global message numbers defined by the public FIT profile, with their profile names. */
export const PROFILE_VERSION = '${version}';

const MESSAGES: ReadonlyArray<readonly [number, string]> = [
${lines}
];

const NAMES = new Map<number, string>(MESSAGES);

/** Profile name for a global message number, or null if the public profile does not define it. */
export function mesgName(globalMesgNum: number): string | null {
  return NAMES.get(globalMesgNum) ?? null;
}

export function isKnownMesgNum(globalMesgNum: number): boolean {
  return NAMES.has(globalMesgNum);
}

export function knownMesgNums(): number[] {
  return MESSAGES.map(([num]) => num);
}
`,
);
console.log(`wrote ${entries.length} message numbers (profile ${version})`);
